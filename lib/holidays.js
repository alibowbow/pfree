// 대한민국 공휴일 (프로토타입용 하드코딩)
// 프로덕션에서는 한국천문연구원 특일정보 Open API(data.go.kr 15012690)로 대체할 것.
// 값은 로컬 날짜 기준 'YYYY-MM-DD'.
export const HOLIDAYS_KR = {
  2025: [
    '2025-01-01', // 신정
    '2025-01-28', '2025-01-29', '2025-01-30', // 설날 연휴
    '2025-03-01', '2025-03-03', // 삼일절 + 대체
    '2025-05-05', '2025-05-06', // 어린이날/부처님오신날 + 대체
    '2025-06-06', // 현충일
    '2025-08-15', // 광복절
    '2025-10-03', // 개천절
    '2025-10-05', '2025-10-06', '2025-10-07', '2025-10-08', // 추석 연휴 + 대체
    '2025-10-09', // 한글날
    '2025-12-25', // 성탄절
  ],
  2026: [
    '2026-01-01', // 신정
    '2026-02-16', '2026-02-17', '2026-02-18', // 설날 연휴 (설날 2/17)
    '2026-03-01', '2026-03-02', // 삼일절(일) + 대체공휴일
    '2026-05-05', // 어린이날
    '2026-05-24', '2026-05-25', // 부처님오신날(일) + 대체
    '2026-06-06', // 현충일
    '2026-08-15', // 광복절
    '2026-09-24', '2026-09-25', '2026-09-26', // 추석 연휴 (추석 9/25)
    '2026-10-03', // 개천절
    '2026-10-09', // 한글날
    '2026-12-25', // 성탄절
  ],
};

/** 여러 해의 공휴일을 Set<'YYYY-MM-DD'> 로 병합 */
export function holidaySet(years = [2025, 2026]) {
  const s = new Set();
  for (const y of years) {
    for (const d of HOLIDAYS_KR[y] || []) s.add(d);
  }
  return s;
}
